-- Estrutura exclusiva do DailyHair. Não executa seeds nem altera dados existentes.
-- Não adicione dailyhair aos schemas expostos pela Data API.
CREATE SCHEMA IF NOT EXISTS dailyhair;
REVOKE ALL ON SCHEMA dailyhair FROM PUBLIC;
SET search_path TO dailyhair;

CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL UNIQUE,
    password text NOT NULL,
    firebase_uid text UNIQUE,
    hair_type text NOT NULL DEFAULT 'Liso',
    curl_pattern text DEFAULT '',
    porosity text NOT NULL DEFAULT 'Média',
    thickness text NOT NULL DEFAULT 'Média',
    needs text DEFAULT '',
    wash_days text,
    bio text,
    profile_image text,
    is_admin smallint NOT NULL DEFAULT 0 CHECK (is_admin IN (0, 1)),
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);
-- Mantém a busca de e-mail sem distinção entre maiúsculas e minúsculas.
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique ON users (lower(email));

CREATE TABLE IF NOT EXISTS products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    brand text NOT NULL,
    category text NOT NULL,
    type text NOT NULL DEFAULT '',
    description text NOT NULL,
    image text,
    status text NOT NULL DEFAULT 'approved',
    created_by bigint REFERENCES users(id),
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment text NOT NULL,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS aprove_products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    brand text NOT NULL,
    category text NOT NULL,
    type text NOT NULL DEFAULT '',
    description text NOT NULL,
    image text,
    created_by bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    status text NOT NULL DEFAULT 'Em análise',
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS wash_routines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    weekday smallint NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    step_order integer NOT NULL DEFAULT 1,
    step_name text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_user_weekday ON wash_routines (user_id, weekday);
CREATE INDEX IF NOT EXISTS idx_reviews_product ON reviews (product_id);
CREATE INDEX IF NOT EXISTS idx_reviews_user ON reviews (user_id);

-- O acesso passa pelo PHP e suas sessões; não por anon/authenticated via API.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE products ENABLE ROW LEVEL SECURITY;
ALTER TABLE reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE aprove_products ENABLE ROW LEVEL SECURITY;
ALTER TABLE wash_routines ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA dailyhair FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA dailyhair FROM PUBLIC;
DO $$
DECLARE role_name text;
BEGIN
    FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
            EXECUTE format('REVOKE ALL ON SCHEMA dailyhair FROM %I', role_name);
            EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA dailyhair FROM %I', role_name);
            EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA dailyhair FROM %I', role_name);
        END IF;
    END LOOP;
END $$;
