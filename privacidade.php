        <h1>Política de Privacidade — DailyHair</h1>
        <div class="updated">Última atualização: 17 de setembro de 2026</div>

        <h2>1. Apresentação</h2>
        <p>Esta Política de Privacidade explica como o <strong>DailyHair</strong>, projeto acadêmico desenvolvido por estudantes do curso de Programador Web do <strong>Senac Minas, em Uberlândia/MG</strong>, trata as informações fornecidas pelos usuários durante a utilização do projeto.</p>
        <p>O objetivo desta política é apresentar, de maneira clara, quais informações podem ser coletadas, para quais finalidades podem ser utilizadas e quais são os direitos dos usuários.</p>

        <h2>2. Sobre o projeto</h2>
        <p>O DailyHair é um <strong>projeto acadêmico desenvolvido por estudantes</strong>, não constituindo atualmente uma empresa independente ou pessoa jurídica criada especificamente para a plataforma.</p>
        <p>O projeto possui finalidade educacional e está sendo desenvolvido no contexto do curso de Programador Web do Senac Minas.</p>
        <div class="contact"><strong>Contato:</strong> dailyhairsenac@gmail.com</div>

        <h2>3. Quais dados podem ser coletados</h2>

        <h3>3.1. Dados de cadastro</h3>
        <p>Podem ser coletados nome, endereço de e-mail, senha armazenada de forma apropriada pelo sistema e informações necessárias para criação e manutenção da conta.</p>

        <h3>3.2. Dados do perfil capilar</h3>
        <p>O usuário poderá fornecer informações relacionadas aos cuidados com seus cabelos, como tipo de cabelo, curvatura, porosidade, espessura, principais necessidades e dias de lavagem.</p>
        <p>Entre as necessidades disponibilizadas atualmente estão:</p>
        <ul>
            <li>Frizz;</li>
            <li>Ressecamento;</li>
            <li>Falta de definição;</li>
            <li>Falta de brilho;</li>
            <li>Queda;</li>
            <li>Quebra;</li>
            <li>Pontas duplas;</li>
            <li>Oleosidade;</li>
            <li>Caspa;</li>
            <li>Danos por química;</li>
            <li>Danos por calor;</li>
            <li>Falta de volume;</li>
            <li>Excesso de volume;</li>
            <li>Cabelo poroso;</li>
            <li>Enfraquecimento;</li>
            <li>Descoloração;</li>
            <li>Manter a hidratação;</li>
            <li>Crescimento saudável.</li>
        </ul>
        <p>Essas informações são fornecidas voluntariamente pelo usuário para utilização das funcionalidades do DailyHair.</p>
        <div class="notice"><strong>Atenção:</strong> caso o projeto passe a coletar informações especificamente relacionadas a diagnósticos, doenças ou outras condições de saúde, esta política deverá ser revisada, pois a LGPD estabelece proteção específica para dados pessoais sensíveis, incluindo dados referentes à saúde.</div>

        <h2>4. Dados relacionados às avaliações e à comunidade</h2>
        <p>Quando o usuário realizar avaliações, comentários ou outras interações no DailyHair, poderão ser armazenadas informações relacionadas a essas atividades.</p>
        <p>Dependendo da funcionalidade, outros usuários poderão visualizar o conteúdo da avaliação ou comentário, o nome ou identificação pública utilizada pelo usuário e algumas características do perfil capilar associadas à interação.</p>
        <p><strong>O endereço de e-mail e a senha do usuário não deverão ser disponibilizados publicamente.</strong></p>

        <h2>5. Dados dos produtos cadastrados</h2>
        <p>Quando o usuário cadastrar um produto, poderão ser armazenadas as informações inseridas no formulário, como nome do produto, marca, categoria, descrição, fotografia e informações relacionadas às avaliações.</p>
        <p>O usuário deve evitar inserir informações pessoais desnecessárias na descrição ou nas fotografias.</p>

        <h2>6. Para que os dados são utilizados</h2>
        <ol>
            <li>Criar e manter a conta do usuário;</li>
            <li>Permitir o acesso ao DailyHair;</li>
            <li>Manter o perfil capilar;</li>
            <li>Personalizar o cronograma capilar;</li>
            <li>Organizar informações relacionadas aos cuidados com os cabelos;</li>
            <li>Permitir avaliações e comentários;</li>
            <li>Permitir o cadastro e consulta de produtos;</li>
            <li>Melhorar o funcionamento e desenvolvimento do projeto;</li>
            <li>Proteger a segurança do sistema;</li>
            <li>Atender solicitações dos usuários relacionadas aos seus dados.</li>
        </ol>
        <p>Os dados não serão utilizados para venda de informações pessoais.</p>

        <h2>7. Bases legais</h2>
        <p>O tratamento de dados pessoais será realizado de acordo com as bases legais aplicáveis previstas na LGPD, considerando a finalidade específica de cada tratamento.</p>
        <p>Dependendo da situação, poderão ser aplicadas bases como execução de procedimentos relacionados à utilização do serviço, consentimento quando necessário, cumprimento de obrigação legal ou regulatória e legítimo interesse quando legalmente aplicável e observados os direitos do titular.</p>

        <h2>8. Quem pode visualizar os dados</h2>
        <p>Determinadas informações são necessárias para o funcionamento interno do DailyHair e poderão ser acessadas pelos responsáveis pelo desenvolvimento e manutenção do projeto, quando necessário.</p>
        <p>Informações destinadas à interação entre usuários poderão ser apresentadas dentro das funcionalidades públicas da plataforma, conforme explicado nesta Política.</p>
        <p>O DailyHair não pretende comercializar ou vender dados pessoais dos usuários.</p>

        <h2>9. Compartilhamento de dados</h2>
        <p>O DailyHair não possui, atualmente, a intenção de compartilhar dados pessoais dos usuários com empresas para fins de publicidade, venda de informações ou criação de perfis comerciais.</p>
        <p>Caso futuramente seja necessário realizar compartilhamento com terceiros, a finalidade e as condições desse tratamento deverão ser avaliadas e, quando necessário, esta Política será atualizada.</p>

        <h2>10. Armazenamento dos dados</h2>
        <p>Na versão acadêmica atualmente utilizada, o projeto utiliza ambiente de desenvolvimento baseado em <strong>XAMPP e banco de dados local</strong>.</p>
        <p>Caso o DailyHair seja posteriormente disponibilizado publicamente na internet ou transferido para outro serviço de hospedagem, poderão existir prestadores responsáveis pela infraestrutura técnica, hospedagem ou armazenamento dos dados.</p>
        <p>Nessa situação, a Política de Privacidade deverá ser atualizada para refletir a infraestrutura efetivamente utilizada.</p>

        <h2>11. Prazo de armazenamento</h2>
        <p>O DailyHair não estabelece atualmente um prazo automático de exclusão baseado apenas no tempo de inatividade da conta.</p>
        <p>Enquanto a conta permanecer ativa, as informações poderão permanecer armazenadas para permitir o funcionamento das funcionalidades correspondentes.</p>
        <p>Quando o usuário excluir sua conta, os dados serão tratados de acordo com a funcionalidade de exclusão e com eventuais obrigações legais aplicáveis.</p>

        <h2>12. Segurança das informações</h2>
        <p>O DailyHair busca adotar medidas técnicas e administrativas adequadas à realidade do projeto para proteger as informações pessoais contra acessos não autorizados, perda, alteração ou utilização indevida.</p>
        <p>Apesar das medidas adotadas, nenhum sistema pode garantir segurança absoluta.</p>

        <h2>13. Cookies e tecnologias semelhantes</h2>
        <p>O DailyHair não utiliza, atualmente, cookies destinados a publicidade comportamental, venda de dados ou ferramentas de rastreamento de terceiros, conforme a estrutura atualmente prevista para o projeto.</p>
        <p>O sistema poderá utilizar recursos técnicos necessários ao funcionamento da sessão e autenticação do usuário, caso sejam necessários para o funcionamento das páginas.</p>
        <p>Caso sejam adicionadas futuramente ferramentas de análise, publicidade, rastreamento ou outros cookies não essenciais, esta Política deverá ser atualizada.</p>

        <h2>14. Crianças e adolescentes</h2>
        <p>O DailyHair não estabelece uma idade mínima específica para utilização da plataforma.</p>
        <p>Caso crianças ou adolescentes utilizem o projeto, o tratamento de seus dados deverá observar as regras específicas da LGPD e o princípio do melhor interesse desse público.</p>

        <h2>15. Direitos dos usuários</h2>
        <p>Nos termos da LGPD, o titular dos dados possui direitos relacionados ao tratamento de seus dados pessoais, observadas as condições e limitações previstas na legislação.</p>
        <p>Entre esses direitos estão, conforme aplicável:</p>
        <ul>
            <li>confirmação da existência de tratamento;</li>
            <li>acesso aos dados;</li>
            <li>correção de dados incompletos, inexatos ou desatualizados;</li>
            <li>informações sobre o tratamento;</li>
            <li>eliminação de dados tratados com base em determinadas hipóteses;</li>
            <li>revogação do consentimento, quando essa for a base legal;</li>
            <li>outros direitos previstos pela legislação.</li>
        </ul>

        <h2>16. Como solicitar informações ou exercer seus direitos</h2>
        <p>O usuário poderá entrar em contato pelo e-mail:</p>
        <div class="contact"><strong>dailyhairsenac@gmail.com</strong></div>
        <p>No contato, recomenda-se informar o nome utilizado no cadastro, o e-mail associado à conta e a solicitação desejada.</p>
        <p>Poderão ser solicitadas informações adicionais para confirmar a identidade do solicitante e proteger os dados contra solicitações realizadas por terceiros.</p>

        <h2>17. Encarregado de dados</h2>
        <p>O DailyHair não possui atualmente uma pessoa formalmente designada como encarregada de proteção de dados.</p>
        <p>O canal disponibilizado para assuntos relacionados à privacidade e proteção de dados é:</p>
        <div class="contact"><strong>dailyhairsenac@gmail.com</strong></div>
        <p>A regulamentação da ANPD prevê situações em que agentes de tratamento de pequeno porte podem ser dispensados da indicação de encarregado, mantendo a necessidade de disponibilizar canal de comunicação com os titulares, conforme o enquadramento e as características efetivas da atividade.</p>

        <h2>18. Exclusão da conta</h2>
        <p>O usuário poderá excluir sua conta por meio da funcionalidade disponibilizada no DailyHair.</p>
        <p>A exclusão poderá resultar na eliminação dos dados associados à conta, respeitadas as situações em que a conservação seja necessária por obrigação legal ou outra hipótese prevista na legislação.</p>
        <p>O DailyHair não exclui contas automaticamente apenas porque permaneceram inativas.</p>

        <h2>19. Alterações desta Política</h2>
        <p><strong>Esta Política de Privacidade poderá ser alterada futuramente.</strong> Isso poderá ocorrer quando houver alterações no funcionamento do DailyHair, novas funcionalidades, mudanças na forma de tratamento dos dados, alterações na infraestrutura de hospedagem ou mudanças relevantes na legislação aplicável.</p>
        <p>Quando houver alteração relevante, a nova versão deverá indicar a respectiva data de atualização.</p>

