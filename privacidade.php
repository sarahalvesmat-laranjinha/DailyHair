        <p>Esta Política de Privacidade é baseada na legislação brasileira aplicável à proteção de dados pessoais, especialmente a <strong>Lei nº 13.709/2018 — Lei Geral de Proteção de Dados Pessoais (LGPD)</strong> e regulamentações aplicáveis da Autoridade Nacional de Proteção de Dados (ANPD).</p>

